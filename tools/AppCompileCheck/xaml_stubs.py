#!/usr/bin/env python3
"""Erzeugt Platzhalter für XAML-generierten Code (InitializeComponent, x:Name-Felder) – nur für die Linux-Prüfung."""
import glob, os, re, sys
import xml.etree.ElementTree as ET

root = sys.argv[1]
out = sys.argv[2]
X = "{http://schemas.microsoft.com/winfx/2006/xaml}"
SPECIAL = {
    "Run": "Microsoft.UI.Xaml.Documents.Run", "Hyperlink": "Microsoft.UI.Xaml.Documents.Hyperlink", "Paragraph": "Microsoft.UI.Xaml.Documents.Paragraph",
    "Ellipse": "Microsoft.UI.Xaml.Shapes.Ellipse", "Rectangle": "Microsoft.UI.Xaml.Shapes.Rectangle", "Path": "Microsoft.UI.Xaml.Shapes.Path",
    "Window": "Microsoft.UI.Xaml.Window", "Application": "Microsoft.UI.Xaml.Application", "ResourceDictionary": "Microsoft.UI.Xaml.ResourceDictionary",
    "KeyboardAccelerator": "Microsoft.UI.Xaml.Input.KeyboardAccelerator",
    "ToggleButton": "Microsoft.UI.Xaml.Controls.Primitives.ToggleButton", "Popup": "Microsoft.UI.Xaml.Controls.Primitives.Popup",
    "RepeatButton": "Microsoft.UI.Xaml.Controls.Primitives.RepeatButton", "Thumb": "Microsoft.UI.Xaml.Controls.Primitives.Thumb",
}

def clr(tag, nsmap):
    if tag.startswith("{"):
        ns, local = tag[1:].split("}")
        if ns.startswith("using:"):
            return ns[6:] + "." + local
        return SPECIAL.get(local, "Microsoft.UI.Xaml.Controls." + local)
    return SPECIAL.get(tag, "Microsoft.UI.Xaml.Controls." + tag)

lines = ["// <auto-generated/> Platzhalter für die Linux-Prüfung (tools/AppCompileCheck)", "#nullable disable"]
for path in sorted(glob.glob(os.path.join(root, "**", "*.xaml"), recursive=True)):
    if "/obj/" in path or "/bin/" in path:
        continue
    tree = ET.parse(path).getroot()
    cls = tree.get(X + "Class")
    if not cls:
        continue
    ns, name = cls.rsplit(".", 1)
    fields = []
    for el in tree.iter():
        n = el.get(X + "Name")
        if n and el is not tree:
            fields.append((clr(el.tag, None), n))
    lines.append(f"namespace {ns} {{ partial class {name} {{")
    lines.append("    private void InitializeComponent() { }")
    lines.append("    private readonly __XBindStub Bindings = new();")
    lines.append("    private sealed class __XBindStub { public void Update() { } public void Initialize() { } public void StopTracking() { } }")
    for t, n in fields:
        lines.append(f"    internal global::{t} {n} = null!;")
    lines.append("} }")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
